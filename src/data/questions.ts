// Comprehensive question definitions for Tracks A, B, C, D
// Compliant with Section 4, 5, 6, 7

export type AnswerMode =
  | 'choose_1'
  | 'choose_up_to_2'
  | 'select_all'
  | 'rate_skills'
  | 'single';

export interface QuestionOption {
  id: string; // 'A', 'B', 'C', etc.
  text: string;
  tags?: string[]; // Archetypes, specialization codes, dimensions, or value tags
  scoreLevel?: 'HIGH' | 'MED' | 'LOW' | 'NONE'; // For Track D
  points?: number; // 100, 60, 30, 0
  isExclusive?: boolean; // For "None yet" or "None of these"
}

export interface QuestionItem {
  id: string; // e.g. 'A-Q1', 'B-Q1', 'C-Q1', 'D-C1'
  track: 'A' | 'B' | 'C' | 'D';
  chipText: string; // e.g. "Real-life case", "Quick check", "Context", "Readiness"
  text: string;
  mode: AnswerMode;
  modeLabel: string; // e.g. "Choose 1", "Choose up to 2", "Select all that apply", "Rate each skill"
  weight: number;
  options: QuestionOption[];
  dimension?: 'ROLE' | 'EVID' | 'TECH' | 'PRACT' | 'NET' | 'POS' | 'AIF'; // For Track D
  isKnowledgeCheck?: boolean; // For Track D (K rule)
  escapeLabel?: string; // default "None of these fit / Not sure"
  escapeValue?: string; // For questions where escape maps to a specific tag
}

